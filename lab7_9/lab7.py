def main():
    """
    Головна функція програми.

    Зчитує з клавіатури розмір квадратної матриці та символ-заповнювач.
    Формує зубчастий список відповідно до заданої зони матриці.
    Результат виводиться на екран та записується у файл KZP.txt.
    """

    #  Ввід розміру матриці
    n_rows = int(input("Введіть розмір квадратної матриці: "))

    #  Ввід символу-заповнювача
    filler = input("Введіть символ-заповнювач: ")

    #  Перевірка: користувач має ввести лише один символ
    if len(filler) != 1:
        print("Помилка: введіть лише один символ!")
        return
    filler = filler[0]  # беремо сам символ

    #  Створення зубчастої матриці
    arr = []

    for i in range(n_rows):
        length = 0  # довжина поточного рядка

        # Рахуємо, скільки елементів має бути в цьому рядку
        for j in range(n_rows):
            if i >= n_rows // 2 and (j >= n_rows - i - 1 and j <= i):
                length += 1

        # Створюємо рядок відповідної довжини, заповнений пробілами
        arr.append([" "] * length)

    print("\nРезультат матриці (зубчастий масив):\n")

    #  Вивід результату на екран і запис у файл
    with open("KZP.txt", "w") as fout:
        for i in range(n_rows):
            index = 0  # індекс для зубчастого масиву

            for j in range(n_rows):
                # Перевірка чи належить елемент заданій зоні
                if i >= n_rows // 2 and (j >= n_rows - i - 1 and j <= i):
                    arr[i][index] = filler
                    print(arr[i][index], end=" ")
                    fout.write(arr[i][index] + " ")
                    index += 1
                else:
                    # Якщо елемент не входить у зону — виводимо пробіл
                    print(" ", end=" ")
                    fout.write("  ")

            # Перехід на новий рядок
            print()
            fout.write("\n")

    print("\nРезультат записано у файл KZP.txt")

if __name__ == "__main__":
    main()
